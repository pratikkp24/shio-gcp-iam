"""Run every demo request through iam.shio (recorded readings, fixed clock) and write demo/data.js for the app.

    .venv/bin/python scripts/export_demo.py

The demo app is a frontend mock: it replays these outcomes instead of calling a model. Each outcome here is what
the Shio program decided for that reading, with every check's result.
"""
import datetime as dt
import json
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE))
os.environ["SHIO_IAM_HOME"] = tempfile.mkdtemp()

from shio_iam import connectors, engine, models, sample_org  # noqa: E402

NOW = dt.datetime(2026, 10, 23, 9, 0, tzinfo=dt.timezone.utc)
REQUESTER = "dan.okafor@northwind.example"
PERSONAS = [REQUESTER, "sam.chen@northwind.example", "maria.lopez@northwind.example", "priya.raman@northwind.example"]
PE = "//bigquery.googleapis.com/projects/nw-analytics/datasets/product_events"
FOOLED = {"give Priya Shah read access to product_events for 30 days": {
    "intent": "grant", "principals": ["priya.shah@northwind.example", "eve.ops@gmail-support.example"],
    "access": "read", "role": "roles/bigquery.dataViewer", "resource": PE, "days": 30}}


def run(request, llm, requester=REQUESTER):
    connectors.use(connectors.MockOrg(None, now=NOW))
    out, record = engine.ask(request, requester, llm)
    rec = json.loads(Path(record).read_text())
    checks = [{"name": c["name"], "passed": c["passed"], "skipped": bool(c.get("skipped")), "detail": c["detail"]}
              for c in rec["checks"]]
    return {"outcome": engine.outcome_of(out), "checks": checks, "reading": rec["readings"][0]["value"],
            "model": rec["readings"][0]["model_id"], "record_sha256": rec["integrity"]["sha256"]}


def main():
    honest = models.scripted()
    requests = [c["request"] for c in json.loads((HERE / "shio_iam" / "scripted.json").read_text())]
    runs = {who: {r: run(r, honest, who) for r in requests} for who in PERSONAS}
    fooled = {who: {k: run(k, models.scripted(FOOLED, name="fooled"), who) for k in FOOLED} for who in PERSONAS}
    data = {"now": NOW.isoformat(), "requester": REQUESTER, "directory": sample_org.DIRECTORY,
            "resources": sample_org.RESOURCES, "policies": sample_org.POLICIES, "deny": sample_org.DENY_POLICIES,
            "personas": PERSONAS, "runs": runs, "fooled": fooled}
    out = HERE / "demo" / "data.js"
    out.write_text("// Generated by scripts/export_demo.py from real iam.shio runs on recorded readings. Do not edit.\n"
                   "window.SHIO_IAM = " + json.dumps(data, indent=1, default=str) + ";\n")
    print(f"wrote {out} ({len(requests)} requests x {len(PERSONAS)} people)")


if __name__ == "__main__":
    main()
